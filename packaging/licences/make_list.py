#!/usr/bin/env python3
"""Writes the third-party crate list that Panna's About box shows (name, version, licence).

Run after any change to Cargo.lock:   python3 packaging/licences/make_list.py
CI runs it with --check and fails if the committed list is out of date.

Every crate the app can be built with is listed, for all platforms, including crates
only used while building. Only the standard library and cargo are needed.
"""

import json
import subprocess
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
OUT = ROOT / "crates" / "panna" / "third-party.tsv"
HEADER = "# Crates Panna is built from, with their licences. Generated by packaging/licences/make_list.py.\n"


def build_list() -> str:
    meta = json.loads(
        subprocess.run(
            ["cargo", "metadata", "--format-version", "1", "--locked"],
            cwd=ROOT,
            check=True,
            capture_output=True,
            text=True,
        ).stdout
    )
    packages = {p["id"]: p for p in meta["packages"]}
    nodes = {n["id"]: n for n in meta["resolve"]["nodes"]}
    workspace = set(meta["workspace_members"])
    app = next(i for i in workspace if packages[i]["name"] == "panna")

    seen, stack = set(), [app]
    while stack:
        node = nodes[stack.pop()]
        for dep in node["deps"]:
            kinds = {k["kind"] for k in dep["dep_kinds"]}
            if kinds <= {"dev"}:
                continue
            if dep["pkg"] not in seen:
                seen.add(dep["pkg"])
                stack.append(dep["pkg"])

    rows = set()
    for pid in seen - workspace:
        p = packages[pid]
        licence = p.get("license") or ("see " + Path(p["license_file"]).name if p.get("license_file") else "unknown")
        rows.add((p["name"], p["version"], licence.replace("/", " OR ")))
    lines = [f"{n}\t{v}\t{l}\n" for n, v, l in sorted(rows, key=lambda r: (r[0].lower(), r[1]))]
    return HEADER + "".join(lines)


def main() -> int:
    text = build_list()
    if "--check" in sys.argv:
        if not OUT.exists() or OUT.read_text(encoding="utf-8") != text:
            print(f"{OUT.relative_to(ROOT)} is out of date: run python3 packaging/licences/make_list.py")
            return 1
        return 0
    OUT.write_text(text, encoding="utf-8", newline="\n")
    print(f"Wrote {text.count(chr(10)) - 1} crates to {OUT.relative_to(ROOT)}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
